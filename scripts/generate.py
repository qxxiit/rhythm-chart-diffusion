"""A new audio file -> playable osu!mania 4K charts (.osz), with the timing given.

    python scripts/generate.py --audio song.mp3 --bpm 174 --offset 1234 --sr 2 3.5 5
    python scripts/generate.py --audio song.mp3 --timing timed.osu --sr 4
    python scripts/generate.py --audio song.mp3 --bpm 174 --offset 1234 --title T --artist A
    python scripts/generate.py --ckpt outputs/full-v2/best.pt --audio song.mp3 --bpm 174 \
        --offset 1234 --sr 4 --genre electronic --mapper <name or user id>
    python scripts/generate.py --ckpt outputs/full-v2/best.pt --list-styles
    python scripts/generate.py --ckpt outputs/full-v4/best.pt --audio song.mp3 --bpm 174 \
        --offset 1234 --sr 4 --stats ln=0.4,jack=0.02      # a long-note chart, few jacks

The model takes the timing as given (design doc §4.4): it places notes on the
beat grid, it does not find the beat. Give either
    --bpm and --offset    one tempo; offset = ms of the first downbeat (osu!'s red line)
    --timing X.osu        the red lines of an .osu (e.g. a map with only timing, made
                          in the osu! editor: the way mappers start anyway)
or neither: then one constant tempo is estimated from the audio (estimate_timing),
printed, and used. That is a guess, not part of the method: it fails on songs
whose tempo changes and can pick half or double time. A wrong offset shifts
every note; a wrong BPM drifts. Check with the metronome in the osu! editor, and
pass the corrected --bpm / --offset.

Audio is decoded as osu! does (src/data/audio.py), turned into log-Mel as in
preprocessing and put on the grid; the whole song is generated by continuation
at each target SR (--sr, several allowed), or chunk by chunk with --mode
independent (no context across chunks: the ablation of queue 3c). Writes to --out (default
outputs/generated/<audio stem>/): the audio, one .osu per SR, and <stem>.osz.
Open the .osz with osu! (lazer: double-click or drag onto the window; stable:
put it in Songs/ and press F5). Quiet bars are thinned by default (--loud-bias 0.1,
quiet side; 0 turns it off), which brought the loudness dynamics of 60 val songs to
the human level with the SR unchanged (EXPERIMENTS 2026-10-06).

Long notes: the model cannot tell from the audio whether a song should be a tap
chart or a long-note chart (it is the mapper's choice: EXPERIMENTS 2026-10-05). With
full-v4, --stats ln=X asks for that share; with any model --hold-bias sets how
readily long notes start (-1: about a third as often, -inf: none). Holds shorter than --min-hold cells
become taps and releases keep --release-gap empty cells before the next press
in their lane (sampler.clean_holds); by default both follow the target SR as in
human charts (sampler.HOLD_RULES: Easy 6 / 5 cells, Normal 5 / 2, Hard and up
3 / 2).

Style (a model trained with --style, src/data/style.py): --genre (a name or id from
--list-styles) and --mapper (a name or user id from the model's vocab, or "other")
choose whose charts to imitate; leave them out for no label. --style-guidance W
pushes harder towards that style (classifier-free guidance, twice the passes).

Chart stats (a model trained with --chart-stats, src/data/chartstats.py): --stats
"ln=0.4,jack=0.05,trill=0.15" asks for that long-note share (of the onsets), jack rate
(of single-note moves within a beat, the same lane again) and trill rate (of two
lane-changing moves in a row, straight back); names left out are the model's choice.
--stats sample takes all three from a random human train chart of about the same SR
(data/chart_stats.csv), printed per SR. --style-guidance W pushes towards the stats
as well (classifier-free guidance, twice the passes; EXPERIMENTS 2026-10-06). Human charts: long-note share median 0.19,
p90 0.47; jacks median 0.03, p90 0.11; trills median 0.14, p90 0.29 (240 val songs, 10-05).
"""

